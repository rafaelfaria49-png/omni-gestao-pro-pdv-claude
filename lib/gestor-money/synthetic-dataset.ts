function buildDefaultCategories(
  perfilId: string,
  tipoPerfil: TipoPerfilFinanceiro,
  extras: Array<{ id: string; nome: string; natureza: "DESPESA" | "RECEITA"; icone: string; cor: string; padrao: boolean }>
): CategoriaGestorMoney[] {
  const base: CategoriaGestorMoney[] = CATEGORIAS_PADRAO_DESPESA.map((c) => ({
    id: `cat-${tipoPerfil.toLowerCase()}-${c.slug}`,
    perfilId,
    tipoPerfil,
    nome: c.nome,
    nomeNormalizado: normalizarNomeCategoria(c.nome),
    natureza: "DESPESA",
    icone: c.icone,
    cor: c.cor,
    padrao: true,
    ativo: true,
    totalPeriodoCentavos: "0",
    quantidadeRegistros: 0,
  }))

  const custom: CategoriaGestorMoney[] = extras.map((c) => ({
    id: c.id,
    perfilId,
    tipoPerfil,
    nome: c.nome,
    nomeNormalizado: normalizarNomeCategoria(c.nome),
    natureza: c.natureza,
    icone: c.icone,
    cor: c.cor,
    padrao: c.padrao,
    ativo: true,
    totalPeriodoCentavos: "0",
    quantidadeRegistros: 0,
  }))

  return [...base, ...custom]
}


function CommandDialog({
  title = 'Command Palette',
  description = 'Search for a command to run...',
  children,
  className,
  showCloseButton = true,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
}) {
  const origemRef = React.useRef<HTMLElement | null>(null)
  return (
    <Dialog {...props}>
      <DialogHeader className="sr-only">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
      </DialogHeader>
      <DialogContent
        className={cn('overflow-hidden p-0', className)}
        showCloseButton={showCloseButton}
        onOpenAutoFocus={() => {
          origemRef.current = document.activeElement instanceof HTMLElement ? document.activeElement : null
        }}
        onCloseAutoFocus={(event) => {
          // CommandDialog é controlado sem DialogTrigger: retoma o diálogo anterior
          // quando ele volta a ser ativo, sem deslocar foco já escolhido por outra janela.
          event.preventDefault()
          const origem = origemRef.current
          if (!origem?.isConnected || origem === document.body || origem.matches(':disabled') || origem.closest('[hidden], [inert], [aria-hidden="true"]')) return
          if (document.activeElement && document.activeElement !== document.body) return
          const outraJanela = Array.from(document.querySelectorAll<HTMLElement>('[role="dialog"], [role="alertdialog"]'))
            .find((el) => el.dataset.state !== 'closed' && !el.closest('[hidden], [aria-hidden="true"]'))
          if (outraJanela && !outraJanela.contains(origem)) return
          if (getComputedStyle(origem).display !== 'none' && getComputedStyle(origem).visibility !== 'hidden') origem.focus()
        }}
      >
        <Command className="[&_[cmdk-group-heading]]:text-muted-foreground **:data-[slot=command-input-wrapper]:h-12 [&_[cmdk-group-heading]]:px-2 [&_[cmdk-group-heading]]:font-medium [&_[cmdk-group]]:px-2 [&_[cmdk-group]:not([hidden])_~[cmdk-group]]:pt-0 [&_[cmdk-input-wrapper]_svg]:h-5 [&_[cmdk-input-wrapper]_svg]:w-5 [&_[cmdk-input]]:h-12 [&_[cmdk-item]]:px-2 [&_[cmdk-item]]:py-3 [&_[cmdk-item]_svg]:h-5 [&_[cmdk-item]_svg]:w-5">
          {children}
        </Command>
      </DialogContent>
    </Dialog>
  )
}


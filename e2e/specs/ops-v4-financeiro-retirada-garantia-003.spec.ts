import { test, expect } from "@playwright/test";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { dismissFirstAccessWizardIfPresent } from "../helpers";

test("garantias por serviço, entrega, aditivo e reimpressão fiel em 1440/768/390", async ({ page, baseURL }) => {
  test.setTimeout(300000);
  if (baseURL !== "http://127.0.0.1:3043") throw new Error("Somente prévia sintética local.");
  const root = path.resolve(__dirname,"../..");
  execFileSync(process.execPath,["--env-file=.env","--import","tsx","test/ops-v4-financeiro-retirada-garantia-003/qa-seed.ts","--reset"],{cwd:root,stdio:"pipe"});
  page.on("dialog",(dialog) => dialog.accept());
  await page.setViewportSize({width:1440,height:1000});
  const lojasProntas = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/stores" && r.ok());
  const ordensProntas = page.waitForResponse((r) => new URL(r.url()).pathname === "/api/ops/ordens" && new URL(r.url()).searchParams.get("lojaId") === "000-qa-frg-001" && r.ok());
  await page.goto("/dashboard/operacoes-v4-preview");
  await Promise.all([lojasProntas,ordensProntas]);
  await page.evaluate(() => { window.print = () => { (window as unknown as { qaPrints: number }).qaPrints = ((window as unknown as { qaPrints: number }).qaPrints || 0) + 1; }; });
  await dismissFirstAccessWizardIfPresent(page);
  await page.getByPlaceholder(/Buscar por Nº da OS/).fill("OS-QA-GARANTIAS");
  const linha = page.getByRole("button").filter({hasText:"OS-QA-GARANTIAS"});
  await expect(linha).toHaveCount(1,{timeout:60000}); await linha.click();
  await page.getByRole("navigation",{name:"Pipeline operacional da OS"}).getByRole("button",{name:/Entrega/}).click();
  const card = page.getByText("🛡 Garantia da OS",{exact:true}).locator("../..");
  await expect(card.getByText("90 dias",{exact:true})).toHaveCount(2);
  await expect(card.getByText("30 dias",{exact:true})).toBeVisible();
  await expect(card.getByRole("spinbutton")).toHaveCount(0);
  await card.getByRole("button",{name:"Ver condições",exact:true}).click();
  await expect(card.getByRole("region",{name:"Condições por serviço"})).toContainText("software");
  await card.getByRole("button",{name:"Alterar prazo",exact:true}).click();
  await card.getByRole("combobox",{name:"Serviço",exact:true}).selectOption("tela-1");
  await card.getByRole("spinbutton").fill("180");
  await card.getByLabel(/Motivo da alteração/).fill("Extensão sintética autorizada");
  await card.getByRole("button",{name:"Salvar garantia"}).click();
  await expect(card.getByText("180 dias",{exact:true})).toBeVisible({timeout:60000});
  await expect(card.getByText("30 dias",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Confirmar entrega real",exact:true}).click();
  await expect(page.getByText("📦 Registro de entrega",{exact:true})).toBeVisible({timeout:60000});
  await page.getByRole("button",{name:"Imprimir Termo de Garantia",exact:true}).click();
  const doc = page.locator("#og-print-root");
  await expect(doc).toContainText("Versão 1");
  const original = await doc.innerText();
  await expect(doc).toContainText("180 dias"); await expect(doc).toContainText("30 dias");
  await page.getByRole("button",{name:"Imprimir",exact:true}).click();
  await page.getByRole("button",{name:"Imprimir",exact:true}).click();
  expect(await page.evaluate(() => (window as unknown as {qaPrints:number}).qaPrints)).toBe(2);
  for (const width of [1440,768,390]) {
    await page.setViewportSize({width,height:1000});
    const dialog = page.locator("[data-og-print-overlay]");
    await dialog.getByRole("button",{name:"Voltar",exact:true}).focus();
    await page.keyboard.press("Shift+Tab");
    expect(await page.evaluate(() => !!document.activeElement?.closest("[data-og-print-overlay]"))).toBe(true);
    for (let i=0;i<7;i++) await page.keyboard.press("Tab");
    expect(await page.evaluate(() => !!document.activeElement?.closest("[data-og-print-overlay]"))).toBe(true);
    expect(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
    await page.screenshot({path:path.join(root,`test/ops-v4-financeiro-retirada-garantia-003/.local/termo-${width}.png`),fullPage:true});
  }
  await page.keyboard.press("Escape"); await expect(doc).toHaveCount(0);
  await expect(page.getByRole("button",{name:"Imprimir Termo de Garantia",exact:true})).toBeFocused();
  await page.setViewportSize({width:1440,height:1000});
  const editor = card.getByRole("button",{name:"Alterar prazo",exact:true});
  if (await editor.getAttribute("aria-expanded") !== "true") await editor.click();
  await card.getByRole("combobox",{name:"Serviço",exact:true}).selectOption("software-1");
  await card.getByRole("spinbutton").fill("60");
  await card.getByLabel(/Motivo da alteração/).fill("Aditivo sintético do software");
  await card.getByRole("button",{name:"Salvar garantia"}).click();
  await expect(card.getByText("60 dias",{exact:true})).toBeVisible({timeout:60000});
  await page.getByRole("button",{name:"Imprimir Termo de Garantia",exact:true}).click();
  await expect(page.getByRole("combobox",{name:"Versão do termo"})).toHaveValue("2");
  await expect(doc).toContainText("60 dias");
  await page.getByRole("combobox",{name:"Versão do termo"}).selectOption("1");
  await expect.poll(() => doc.innerText()).toBe(original);
  await page.getByRole("button",{name:"Voltar",exact:true}).click();
});
